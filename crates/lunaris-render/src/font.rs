/// The glyph for a character; anything outside printable ASCII shows as `?`.
pub fn glyph(c: char) -> &'static [u8; 5] {
    let i = if (' '..='~').contains(&c) { c as usize - 32 } else { '?' as usize - 32 };
    &GLYPHS[i]
}

/// Whether the pixel (`col` 0..5, `row` 0..8) of a glyph is lit.
pub fn lit(g: &[u8; 5], col: usize, row: usize) -> bool {
    col < GLYPH_W && row < GLYPH_H && (g[col] >> row) & 1 == 1
}

/// Replace `{#key}` in a text by the translation of `key`; `lookup` gives the text of a key (or `None`: the key itself is shown).
pub fn translate(text: &str, lookup: impl Fn(&str) -> Option<String>) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(open) = rest.find("{#") {
        out.push_str(&rest[..open]);
        let after = &rest[open + 2..];
        match after.find('}') {
            Some(close) if !after[..close].is_empty() && !after[..close].contains('{') => {
                let key = &after[..close];
                out.push_str(&lookup(key).unwrap_or_else(|| key.to_string()));
                rest = &after[close + 1..];
            }
            _ => {
                out.push_str("{#");
                rest = after;
            }
        }
    }
    out.push_str(rest);
    out
}

/// Replace `{name}` in a template with the value of the world resource of that name (whole numbers print without a
/// decimal point, others with two decimals; an unset resource reads 0). Anything else is copied as it is.
pub fn expand_template(template: &str, resource: impl Fn(&str) -> Option<f64>) -> String {
    let mut out = String::with_capacity(template.len());
    let mut rest = template;
    while let Some(open) = rest.find('{') {
        out.push_str(&rest[..open]);
        let after = &rest[open + 1..];
        match after.find('}') {
            Some(close) if lunaris_ecs::valid_resource_name(&after[..close]) => {
                let v = resource(&after[..close]).unwrap_or(0.0);
                if v.fract() == 0.0 && v.abs() < 1e15 {
                    out.push_str(&format!("{}", v as i64));
                } else {
                    out.push_str(&format!("{v:.2}"));
                }
                rest = &after[close + 1..];
            }
            _ => {
                out.push('{');
                rest = after;
            }
        }
    }
    out.push_str(rest);
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn translations_replace_keys_and_leave_the_rest() {
        let t = |k: &str| (k == "hello").then(|| "Hallo".to_string());
        assert_eq!(translate("{#hello}, {#who}! {x} {#} {#open", t), "Hallo, who! {x} {#} {#open");
        assert_eq!(translate("plain", t), "plain");
    }

    #[test]
    fn letters_look_like_themselves() {
        // an 'I' has a vertical stroke through the middle column and a base and cap; a '.' is only low
        let i = glyph('I');
        assert!((0..7).all(|r| lit(i, 2, r)));
        let dot = glyph('.');
        assert!(!lit(dot, 3, 0) && lit(dot, 3, 5) && lit(dot, 3, 6));
        assert_eq!(glyph('é'), glyph('?'), "unknown characters show as ?");
        // every glyph other than space lights at least one pixel and none uses more than 8 rows
        for c in '!'..='~' {
            assert!(glyph(c).iter().any(|&b| b != 0), "{c}");
        }
        assert!(glyph(' ').iter().all(|&b| b == 0));
    }

    #[test]
    fn templates_fill_in_resources() {
        let res = |n: &str| match n {
            "score" => Some(12.0),
            "time.left" => Some(4.256),
            _ => None,
        };
        assert_eq!(expand_template("Score: {score}", res), "Score: 12");
        assert_eq!(expand_template("{time.left}s / {missing}", res), "4.26s / 0");
        assert_eq!(expand_template("{ not a name } and {unclosed", res), "{ not a name } and {unclosed");
        assert_eq!(expand_template("plain", res), "plain");
    }
}
