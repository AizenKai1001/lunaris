"""Read the colours Visual Studio Code uses when a theme says nothing, and the four dark themes it ships, out of an installed VS Code.

    python -I tools/extract_vscode_defaults.py [path to the VS Code folder with resources/app]

Writes crates/lunaris-studio/src/vsc_defaults.rs (the dark default of every colour that has a plain value) and copies the theme files
(MIT licence, the vscode repository) into crates/lunaris-studio/assets/vscode/. The Script tab of the editor draws with them, so that it looks
the way VS Code looks. Only reads the install; nothing of it is changed.
"""
import glob
import io
import os
import re
import shutil
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def find_install():
    if len(sys.argv) > 1:
        return sys.argv[1]
    base = os.path.join(os.environ.get("LOCALAPPDATA", ""), "Programs", "Microsoft VS Code")
    cands = glob.glob(os.path.join(base, "*", "resources", "app", "package.json"))
    if not cands:
        sys.exit("no VS Code found under " + base)
    cands.sort(key=os.path.getmtime)
    return os.path.dirname(cands[-1])


app = find_install()
js = io.open(os.path.join(app, "out", "vs", "workbench", "workbench.desktop.main.js"), encoding="utf-8", errors="replace").read()
# registerColor("name", { dark: "#...", ... }, ...)
found = {}
for m in re.finditer(r'\w+\("([A-Za-z][A-Za-z0-9]*(?:\.[A-Za-z0-9]+)+)",\{([^{}]*)\}', js):
    name, body = m.group(1), m.group(2)
    d = re.search(r'dark:"(#[0-9a-fA-F]{3,8})"', body)
    if d and name not in found:
        found[name] = d.group(1)
print(len(found), "colours with a plain dark default")
out = ["//! Generated by tools/extract_vscode_defaults.py from Visual Studio Code: the dark default of every colour that has a plain value.", "//! (VS Code is MIT licensed; these are the colours its theme system falls back to when a theme leaves one out.)", "", "pub const DARK_DEFAULTS: &[(&str, &str)] = &["]
for k in sorted(found):
    out.append(f'    ("{k}", "{found[k]}"),')
out.append("];")
io.open(os.path.join(ROOT, "crates", "lunaris-studio", "src", "vsc_defaults.rs"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")

dest = os.path.join(ROOT, "crates", "lunaris-studio", "assets", "vscode")
os.makedirs(dest, exist_ok=True)
for n in ("dark_vs", "dark_plus", "dark_modern", "2026-dark"):
    shutil.copyfile(os.path.join(app, "extensions", "theme-defaults", "themes", n + ".json"), os.path.join(dest, n + ".json"))
print("themes copied to", dest)
